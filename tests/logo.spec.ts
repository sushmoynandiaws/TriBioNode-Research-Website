import { expect, test } from '@playwright/test'

test('navbar keeps the gentle TriFold and shares the overview pause control', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  const mark = page.locator('.site-header .brand-motion')
  const footerMark = page.locator('.site-footer .brand-motion')
  await expect(mark).toHaveCSS('animation-play-state', 'running')
  await expect(footerMark).toHaveCSS('animation-play-state', 'paused')
  const initial = await mark.evaluate(element => getComputedStyle(element).transform)
  await expect.poll(() => mark.evaluate(element => getComputedStyle(element).transform)).not.toBe(initial)
  await page.getByRole('button', { name: 'Pause animation' }).click()
  await expect(mark).toHaveCSS('animation-play-state', 'paused')
  await page.getByRole('button', { name: 'Play animation' }).click()
  await expect(mark).toHaveCSS('animation-play-state', 'running')
  await footerMark.scrollIntoViewIfNeeded()
  await expect(footerMark).toHaveCSS('animation-play-state', 'running')
  await page.getByRole('link', { name: 'TriBioNode home' }).first().click()
  await expect(footerMark).toHaveCSS('animation-play-state', 'paused')
})

test('the tab icon uses the same rendered TriFold and static fallback remains usable', async ({ page, request }) => {
  await page.route('**/brand/trifold-gentle.webp', route => route.fulfill({ status: 404, body: '' }))
  await page.goto('/')
  const mark = page.locator('.site-header .brand-still')
  await expect(mark).toBeVisible()
  expect(await mark.evaluate(element => (element as HTMLImageElement).naturalWidth)).toBe(64)
  const favicon = await page.locator('link[rel="icon"]').getAttribute('href')
  expect(favicon).toBe('./brand/trifold-rendered-icon.png')
  const response = await request.get(favicon!)
  expect(response.ok()).toBe(true)
  expect(response.headers()['content-type']).toContain('image/png')
})
