import { expect, test } from '@playwright/test'

test('TriFold animation can pause, resume, and stop outside the viewport', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  const video = page.locator('.trifold-media video')
  const mark = page.locator('.site-header .brand-motion')
  await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).currentTime)).toBeGreaterThan(.1)
  await expect(mark).toHaveCSS('animation-play-state', 'running')
  const initialFrame = await mark.evaluate(element => getComputedStyle(element).transform)
  await expect.poll(() => mark.evaluate(element => getComputedStyle(element).transform)).not.toBe(initialFrame)
  const firstImage = await page.locator('.site-header .brand-mark').screenshot({ animations: 'allow' })
  await expect.poll(async () => (await page.locator('.site-header .brand-mark').screenshot({ animations: 'allow' })).equals(firstImage)).toBe(false)
  await page.getByRole('button', { name: 'Pause logo animation' }).click()
  await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).paused)).toBe(true)
  await expect(mark).toHaveCSS('animation-play-state', 'paused')
  await page.getByRole('button', { name: 'Play logo animation' }).click()
  await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).paused)).toBe(false)
  await expect(mark).toHaveCSS('animation-play-state', 'running')
  await page.locator('#explorer').scrollIntoViewIfNeeded()
  await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).paused)).toBe(true)
  await page.getByRole('link', { name: 'TriBioNode home' }).first().click()
  await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).paused)).toBe(false)
})

test('reduced motion starts still and pauses a playing logo when enabled', async ({ page }) => {
  await page.goto('/')
  const video = page.locator('.trifold-media video')
  await expect(page.getByRole('button', { name: 'Play logo animation' })).toBeVisible()
  await expect(page.locator('.site-header .brand-motion')).toHaveCSS('animation-name', 'none')
  expect(await video.evaluate(element => (element as HTMLVideoElement).paused)).toBe(true)
  expect(await video.evaluate(element => (element as HTMLVideoElement).currentTime)).toBe(0)
  await page.getByRole('button', { name: 'Play logo animation' }).click()
  await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).currentTime)).toBeGreaterThan(.1)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.getByRole('button', { name: 'Play logo animation' })).toBeVisible()
  await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).paused)).toBe(true)
})

test('MP4 plays when WebM is unavailable', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.route('**/brand/*.webm', route => route.fulfill({ status: 404, body: '' }))
  await page.goto('/')
  const video = page.locator('.trifold-media video')
  await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).currentTime)).toBeGreaterThan(.1)
  expect(await video.evaluate(element => (element as HTMLVideoElement).currentSrc)).toContain('.mp4')
})

test('a failed animation retains the static TriFold and usable navigation', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.route('**/brand/*.{webm,mp4}', route => route.fulfill({ status: 404, body: '' }))
  await page.goto('/')
  await expect(page.locator('.trifold-media video')).toHaveCount(0)
  const poster = page.locator('.trifold-media img')
  await expect(poster).toBeVisible()
  expect(await poster.evaluate(element => (element as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Play logo animation' }).click()
  await expect(page.locator('.site-header .brand-motion')).toHaveCSS('animation-play-state', 'running')
  await page.getByRole('button', { name: 'Pause logo animation' }).click()
  await expect(page.locator('.site-header .brand-motion')).toHaveCSS('animation-play-state', 'paused')
  await page.getByRole('link', { name: 'Explore the model architecture' }).click()
  await expect(page).toHaveURL(/#architecture$/)
})

test('the tab icon uses the same rendered TriFold and static fallback remains usable', async ({ page, request }) => {
  await page.route('**/brand/trifold-gentle.webp', route => route.fulfill({ status: 404, body: '' }))
  await page.goto('/')
  const mark = page.locator('.site-header .brand-still')
  await expect(mark).toBeVisible()
  expect(await mark.evaluate(element => (element as HTMLImageElement).naturalWidth)).toBe(64)
  const favicon = await page.locator('link[rel="icon"]').getAttribute('href')
  expect(favicon).toBe('./brand/trifold-rendered-icon.png')
  const response = await request.get(favicon!)
  expect(response.ok()).toBe(true)
  expect(response.headers()['content-type']).toContain('image/png')
})
